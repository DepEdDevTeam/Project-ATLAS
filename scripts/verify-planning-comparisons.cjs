const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../lib/agents/planning-contract.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject });
const origin = process.env.ATLAS_VERIFY_ORIGIN || 'http://localhost:3003';
(async () => {
  console.log('Running the complete workflow to verify scope-specific comparison prose.');
  const response = await fetch(`${origin}/api/agents/run`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(exportsObject.defaultConfiguration), signal: AbortSignal.timeout(600000) });
  const run = await response.json();
  assert.ok(response.ok, JSON.stringify(run));
  const evidence = run.claimCalculationEvidence.flatMap(domain => domain.calculations);
  const ids = evidence.map(calculation => calculation.id);
  assert.equal(new Set(ids).size, ids.length);
  const selected = run.results[0].calculations.find(c => c.id === 'learner-demand').value;
  const higher = run.alternatives.find(s => s.id === 'higher-demand').results[0].calculations.find(c => c.id === 'learner-demand').value;
  assert.equal(evidence.find(c => c.id === 'alternative:higher-demand:learner-demand').value, higher);
  assert.ok(higher > selected);
  assert.ok(run.report.claims.every(claim => claim.calculationIds.every(id => ids.includes(id)) && !claim.reviewRequired));
  const comparisonClaims = run.report.claims.filter(claim => claim.calculationIds.some(id => /^(alternative|year):/.test(id)));
  assert.ok(comparisonClaims.length, `No reviewed comparison survived reporting. Inspect run ${run.id}.`);
  assert.equal(run.reporter.mode, 'model', run.reporter.error);
  assert.equal(run.reporterReview.status, 'reviewed', run.reporterReview.error);
  assert.notEqual(run.validation.status, 'failed');
  const exported = await fetch(`${origin}/api/agents/runs?id=${run.id}&format=html`);
  assert.equal(exported.status, 200);
  const html = await exported.text();
  assert.ok(html.includes('Executive calculation citation register'));
  assert.ok(comparisonClaims.every(claim => claim.calculationIds.every(id => html.includes(id))));
  console.log(JSON.stringify({ runId: run.id, selectedDemand: selected, higherDemand: higher, reviewedComparisonClaims: comparisonClaims.length, citations: comparisonClaims.map(claim => claim.calculationIds) }));
  console.log('Scoped comparison API-to-agent-to-reviewed-report verification passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
